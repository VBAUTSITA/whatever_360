// Local USERTEST/FREEPDB1 integration only. Requires OracleBrowserFixture on localhost.
// Uses the real HTTP controller/service/repository/Nashorn path, without response substitution.
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const fs = require('node:fs');
const assert = require('node:assert/strict');
const base = process.env.AUDITORIA_ORACLE_URL || 'http://127.0.0.1:3299/tracker';
let browser;
(async () => {
  fs.mkdirSync('target/browser/oracle', { recursive: true });
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1500, height: 1100 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  async function query(action) {
    const pending = page.waitForResponse(r => r.url().includes('/dashboard/api/consultar') && r.request().method() === 'POST', {timeout:90000});
    await action(); const response = await pending;
    assert.equal(response.status(), 200, await response.text());
    const data = await response.json();
    await page.waitForFunction(() => document.getElementById('ad-panel').getAttribute('aria-busy') === 'false');
    return data;
  }
  await page.goto(base + '/auditoria-red/dashboard');
  await page.locator('#ad-filter-tipo').waitFor();
  assert.equal(await page.locator('nav a[aria-current="page"]').textContent(), 'Panel PCI');
  await page.screenshot({path:'target/browser/oracle/initial-desktop.png',fullPage:true});
  await page.locator('#ad-site').fill('AUDRED');
  await page.locator('#ad-suggestions button').first().waitFor();
  await page.locator('#ad-site').press('ArrowUp');
  assert.equal(await page.locator('#ad-site').getAttribute('aria-activedescendant'), await page.locator('#ad-suggestions button').last().getAttribute('id'));
  await page.locator('#ad-site').press('ArrowDown');
  await page.locator('#ad-site').press('Enter');
  assert.equal(await page.locator('#ad-lat').inputValue(), '-12.09');
  await page.locator('#ad-4g').check();
  await page.locator('#ad-radius').fill('1');
  const result = await query(() => page.locator('#ad-run').click());
  assert(result.totalHallazgos > 25);
  assert.equal(result.hallazgos.length, 25);
  assert(result.resumen.some(r=>r.tecnologia === '4G'));
  assert(result.resumen.some(r=>r.tecnologia === '5G'));
  assert(result.resumen.every(r=>r.celdasSinFrecuencia > 0));
  assert(result.resumen.some(r=>r.taInvalido > 0));
  assert(result.resumen.some(r=>r.taAusente > 0));
  assert(result.resumen.some(r=>r.duplicadasConflictivas > 0));
  assert(result.celdas.some(c=>c.estadoTa === 'INVALIDO'));
  assert(result.celdas.some(c=>c.estadoTa === 'AUSENTE'));
  assert(result.hallazgos.every(h=>h.evidenciaFrecuencia === 'FRECUENCIA_NO_VERIFICADA'));
  await page.locator('#ad-findings tr').first().focus();
  await page.locator('#ad-findings tr').first().press('Enter');
  const pair = await page.locator('#ad-map-note').textContent();
  await query(() => page.locator('#ad-next').click());
  assert.equal(await page.locator('#ad-map-note').textContent(), pair);
  await query(() => page.locator('#ad-filter-tipo').selectOption({label:'Colisión PCI potencial'}));
  assert.equal(await page.locator('#ad-map-note').textContent(), pair);
  assert.equal(Number((await page.locator('#ad-count-findings').textContent()).replace(/\D/g,'')), result.totalHallazgos);
  await query(() => page.locator('#ad-target').selectOption({label:'5G · AUDRED_5G_MISSING'}));
  const neighbors = await query(() => page.locator('#ad-neighbor-limit').fill('200').then(()=>page.locator('#ad-neighbor-limit').press('Tab')));
  assert(neighbors.vecinos.some(v=>v.celda.dentroArea === false));
  const invalid = page.locator('#ad-neighbors tr[data-selectable]').filter({hasText:'AUDRED_5G_INVALID'});
  await invalid.focus(); await invalid.press('Enter');
  assert((await page.locator('#ad-pair-evidence').textContent()).includes('TA inválido'));
  assert((await page.locator('#ad-pair-evidence').textContent()).includes('Sin TA'));
  assert((await page.locator('#ad-pair-evidence').textContent()).includes('Respaldo por vecinas'));
  await page.locator('#ad-map-context').check();
  assert((await page.locator('#ad-context-note').textContent()).includes('Contexto visible'));
  await page.locator('#ad-map-context').uncheck();
  assert((await page.locator('#ad-context-note').textContent()).includes('Contexto opcional'));
  await page.locator('.ad-trace summary').click();
  assert((await page.locator('#ad-engines').textContent()).includes('Duplicadas con conflicto'));
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:'target/browser/oracle/dense-selected-evidence-desktop.png',fullPage:true});
  await query(()=>page.locator('#ad-filter-celda').fill('NO_MATCH_ORACLE'));
  assert.equal(await page.locator('#ad-count-filtered').textContent(), '0');
  assert((await page.locator('#ad-findings').textContent()).includes('No certifica'));
  assert.equal(await page.locator('#ad-neighbors tr[data-selectable]').count(), neighbors.vecinos.length);
  await page.screenshot({path:'target/browser/oracle/empty-desktop.png',fullPage:true});
  await query(()=>page.locator('#ad-reset').click());
  const sparse = await query(()=>page.locator('#ad-target').selectOption({label:'5G · AUDRED_5G_SPARSE'}));
  assert.equal(sparse.objetivo.radioM, null);
  assert.equal(sparse.objetivo.fuenteRadio, 'SIN_VECINAS');
  assert.equal(sparse.vecinos.length, 0);
  assert((await page.locator('#ad-pair-evidence').textContent()).includes('Sin vecinas para respaldo'));
  assert((await page.locator('#ad-pair-evidence').textContent()).includes('sin inventar sectores'));
  await page.locator('.ad-detail-grid .ad-card').nth(1).screenshot({path:'target/browser/oracle/sparse-unknown-range.png'});
  const overflow = await query(()=>page.locator('#ad-target').selectOption({label:'5G · AUDRED_5G_OVERFLOW'}));
  assert.equal(overflow.objetivo.radioM, null);
  assert.equal(overflow.objetivo.fuenteRadio, 'TA_DESBORDAMIENTO_DESCONOCIDO');
  assert((await page.locator('#ad-pair-evidence').textContent()).includes('alcance desconocido'));
  await page.locator('.ad-detail-grid .ad-card').nth(1).screenshot({path:'target/browser/oracle/overflow-unknown-range.png'});
  await query(()=>page.locator('#ad-target').selectOption({label:'5G · AUDRED_5G_MISSING'}));
  await invalid.focus(); await invalid.press('Enter');
  await page.setViewportSize({width:390,height:844});
  assert(await page.evaluate(()=>document.documentElement.scrollWidth <= innerWidth+1));
  await page.screenshot({path:'target/browser/oracle/selected-evidence-mobile.png',fullPage:true});
  assert.deepEqual(errors, []);
  fs.writeFileSync('target/browser/oracle/result.json', JSON.stringify({passed:true,source:'USERTEST/FREEPDB1 local Oracle fixture via actual repositories, synthetic labeled rows',scenarios:['real 4G/5G repository HTTP query','keyboard site and pair selection','dense pagination','frequency/TA/dedup evidence','selected pair survives filters','full geographic neighbor margin','missing and invalid TA fallback detail','optional context markers','engine source fingerprint trace','empty filters preserve neighbors','sparse no-neighbor point without invented sector','open TA bin unknown range','390px mobile overflow'],totalHallazgos:result.totalHallazgos,celdasArea:result.celdas.length,resumen:result.resumen,vecinas:neighbors.vecinos.length,pageErrors:errors}, null, 2));
  console.log('PASS: Oracle dashboard browser integration, '+result.totalHallazgos+' findings, '+result.celdas.length+' area cells, desktop/mobile evidence screenshots');
  await browser.close();
})().catch(async error=>{console.error(error);if(browser)await browser.close();process.exitCode=1;});
